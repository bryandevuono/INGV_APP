library;

import 'package:ingv_app/data/models/event_model.dart';

/// Compact row representation for seed event data.
class _SeedRow {
  final int idOffset;
  final String category;
  final int startDays;
  final int startHours;
  final int startMinutes;
  final int? endDays;
  final int? endHours;
  final int? endMinutes;
  final double lat;
  final double lon;
  final String title;
  final String tag;
  final String description;
  final String? groupId;

  const _SeedRow({
    required this.idOffset,
    required this.category,
    required this.startDays,
    this.startHours = 0,
    this.startMinutes = 0,
    required this.endDays,
    this.endHours,
    this.endMinutes,
    required this.lat,
    required this.lon,
    required this.title,
    required this.tag,
    required this.description,
    this.groupId,
  });

  DateTime _offset(int days, int hours, int minutes) => DateTime(
    2026,
    5,
    20,
  ).add(Duration(days: days, hours: hours, minutes: minutes));

  EventModel toEvent() => EventModel(
    eventId: 900000 + idOffset,
    category: category,
    startDt: _offset(startDays, startHours, startMinutes),
    endDt: endDays != null
        ? _offset(endDays!, endHours ?? 0, endMinutes ?? 0)
        : null,
    author: 'DemoSeed',
    lat: lat,
    long: lon,
    title: title,
    tag: tag,
    description: description,
    groupId: groupId,
  );
}

